ABSTRACT = (
"Amorphous-nanocrystalline (AN) composites have been proposed as a route to damage-tolerant Mg-Zn-Ca alloys for "
"biodegradable implants, but how composition and nanocrystal content set their strength is not known at the atomic "
"scale. We ran 48 molecular dynamics tensile simulations of 20 nm cells (about 380,000 atoms) with a "
"second-nearest-neighbor modified embedded-atom potential. They cover ten compositions, pure-glass controls, "
"nanocrystal volume fractions of 5–19% with packing replicates, seed radius, strain rate and temperature. Peak "
"strength rose by 17.9% from xCa = 0.03 to 0.07 in the pure glass, so calcium strengthens the glass matrix itself. "
"Nanocrystals lowered the peak strength by 1.16% per percentage point of volume fraction, against a packing scatter "
"of 0.3–0.5%, and also lowered Young’s modulus although the crystal is stiffer than the glass. At fixed volume "
"fraction, larger seeds gave stronger composites. Peak strength fell by 0.245% per kelvin between 250 and 400 K and "
"rose by 10.3% per doubling of strain rate. No discrete shear band formed in any glass or composite cell. Incremental "
"non-affine displacement instead showed a steady population of small rearrangement clusters and a 20–40% excess of "
"non-affine motion at the interphase, largest before the peak. Calcium atoms carried 1.5–1.6 times the "
"volume-normalized von Mises stress of zinc atoms, and local structure, mainly atomic volume and bond length, "
"predicted 81–88% of that difference. A Gaussian process surrogate placed 16 of 17 informative held-out simulations "
"inside its 95% intervals."
)

